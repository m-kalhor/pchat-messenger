/** The flag emoji of an ISO code (two regional-indicator letters). */
export const flag = (iso) => String.fromCodePoint(...[...iso].map((c) => 0x1f1a5 + c.charCodeAt(0)));

/** "+98" and the national number typed without its leading 0 (also takes 0912…, 98912… or a pasted +98…) -> "+98912…". */
export function joinPhone(dial, typed) {
  let d = String(typed || '').replace(/[۰-۹]/g, (c) => c.charCodeAt(0) - 0x6f0).replace(/[٠-٩]/g, (c) => c.charCodeAt(0) - 0x660);
  const plus = /^\s*(\+|00)/.test(d);
  d = d.replace(/\D/g, '');
  if (plus) { if (d.startsWith('00')) d = d.slice(2); return '+' + d; }
  d = d.replace(/^0+/, '');
  return '+' + dial + d;
}
